#!/usr/bin/env python3
"""Write cht/system/balanceFunctions: the function objects for the energy and mass books.
Per patch: sum(phi) [kg/s], weightedSum(h) weighted by phi [W, enthalpy flow relative to Tstd],
areaIntegrate(qr) [W, net radiation absorbed by the surface, beam counted negative at the window];
per region: wallHeatFlux (= alpha*snGrad(h) - qr per patch, wallHeatFlux.C:80,92), T min/max,
h residuals; outlet bulk T; front/back face T. Tamb and energyAudit: system/auditFunctions."""
import sys
patches = {
    'inletRegion':  ['inlet', 'opticalWindow', 'inletWall', 'inletRegion_to_porousRegion'],
    'porousRegion': ['porousWall', 'porousRegion_to_inletRegion', 'porousRegion_to_exitRegion'],
    'exitRegion':   ['exitWall', 'exitRegion_to_porousRegion', 'outlet'],
}
flowPatches = {'inlet', 'opticalWindow', 'outlet', 'inletRegion_to_porousRegion', 'porousRegion_to_inletRegion',
               'porousRegion_to_exitRegion', 'exitRegion_to_porousRegion'}
out = ['// generated by scripts/genFunctions.py - included in system/controlDict functions{}', '']
w = out.append
def sfv(name, region, patch, op, fields, extra='', every=20):
    w(f'''{name}
{{
    type            surfaceFieldValue;
    libs            (fieldFunctionObjects);
    region          {region};
    regionType      patch;
    name            {patch};
    operation       {op};
    fields          ({fields});{extra}
    writeFields     false;
    writeControl    timeStep;
    writeInterval   {every};
    log             false;
}}''')
# Tamb (outlet surroundings) is created by the coded function object in system/auditFunctions
for R, plist in patches.items():
    w(f'''residuals_{R}
{{
    type            solverInfo;
    libs            (utilityFunctionObjects);
    region          {R};
    fields          (h);
    writeResidualFields no;
    writeControl    timeStep;
    writeInterval   1;
}}
Trange_{R}
{{
    type            fieldMinMax;
    libs            (fieldFunctionObjects);
    region          {R};
    fields          (T);
    mode            magnitude;
    location        false;
    writeControl    timeStep;
    writeInterval   20;
    log             false;
}}
wallHeatFlux_{R}
{{
    type            wallHeatFlux;
    libs            (fieldFunctionObjects);
    region          {R};
    patches         ({" ".join(p for p in plist if p not in ('inlet', 'opticalWindow', 'outlet'))});
    qr              qr;
    executeControl  timeStep;     // computed and written in execute() (wallHeatFlux.C)
    executeInterval 20;
    writeControl    writeTime;
    log             false;
}}''')
    for p in plist:
        if p in flowPatches:
            sfv(f'mdot_{p}', R, p, 'sum', 'phi', every=1000)
            sfv(f'H_{p}', R, p, 'weightedSum', 'h', '\n    weightField     phi;')
        sfv(f'Qr_{p}', R, p, 'areaIntegrate', 'qr')
sfv('outletBulkT', 'exitRegion', 'outlet', 'weightedAverage', 'T', '\n    weightField     phi;')
for p, R in [('porousRegion_to_inletRegion', 'porousRegion'), ('porousRegion_to_exitRegion', 'porousRegion')]:
    sfv(f'Tmax_{p}', R, p, 'max', 'T')
    sfv(f'Tmean_{p}', R, p, 'areaAverage', 'T')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
