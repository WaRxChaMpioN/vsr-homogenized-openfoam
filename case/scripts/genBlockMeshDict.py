#!/usr/bin/env python3
"""Write the single-region blockMeshDict (one mesh for the whole channel, three cellZones).

Cross-section: 3x3 blocks, 12 cells graded 2.5 in each 12.5 mm wall band, 20 uniform cells over the window band,
window edges at 12.5/37.5 mm on block faces.
Axial:  inletRegion  x =   0- 75 mm, 48 cells, multi-graded 3.49 -> 1.0 mm (0-70) and 1.0 -> 0.081 mm (70-75)
        porousRegion x =  75-125 mm, 30 cells, 0.61 -> 3.45 -> 0.61 mm (graded towards BOTH faces)
        exitRegion   x = 125-275 mm, 30 cells, 2.30 -> 9.19 mm (gX 4, as now)
The 0.081 mm upstream face cell keeps the cell Peclet number U*dx/alpha_air below 2 at Re 900, so
the outflow through the hot, opaque front face stays bounded (see outflow_face_1d.py).
The porous zone is fine at both ends because the cell-centre velocity wiggles in the 2-3 cells next
to a resistance jump (the face fluxes stay exact). With the old one-sided grading (last cell 4.88 mm)
the Darcy-Forchheimer sink integrated to 7.26 Pa instead of 7.50 Pa at Re 300.

    genBlockMeshDict.py [blockMeshDict] [scale]

scale multiplies every cell count with the same gradings (the mesh study of Table 3: 0.75 gives
33 x 33 x 80 = 87,120 cells, 1.25 gives 55 x 55 x 136 = 411,400 cells; default 1, 209,088 cells)."""
import sys
f = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0
n = lambda c: round(c * f)
xs = [0.0, 75.0, 125.0, 275.0]
yz = [0.0, 12.5, 37.5, 50.0]
zones = ['inletRegion', 'porousRegion', 'exitRegion']
walls = ['inletWall', 'porousWall', 'exitWall']
axial = [
    (str(n(48)), '((0.9333333333 0.7291666667 0.2857142857) (0.0666666667 0.2708333333 0.08))'),
    (str(n(30)), '((0.5 0.5 5.6535) (0.5 0.5 0.176882))'),
    (str(n(30)), '4'),
]
def v(s, j, k):          # station s (x), j: y index, k: z index
    return 16*s + 4*k + j
out = []
w = out.append
w('''/*--------------------------------*- C++ -*----------------------------------*\\
  =========                 |
  \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox
   \\\\    /   O peration     |
    \\\\  /    A nd           |
     \\\\/     M anipulation  |
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}
// ONE mesh for the whole channel (generated by genBlockMeshDict.py).
// cellZones inletRegion / porousRegion / exitRegion become the CHT regions after
// 'splitMeshRegions -cellZonesOnly'. Coordinates in mm.

scale 0.001;

nW      @NW@;     // cells in each 12.5 mm wall band (graded 2.5; 0.63 mm at the wall at scale 1)
gW      2.5;
gWr     0.4;
nC      @NC@;     // 25 mm window band, uniform

vertices
(''')
for s, x in enumerate(xs):
    for k, z in enumerate(yz):
        for j, y in enumerate(yz):
            w(f'    ({x:g} {y:g} {z:g})    // {v(s, j, k)}')
w(');\n\nblocks\n(')
nyz = ['$nW', '$nC', '$nW']; gyz = ['$gW', '1', '$gWr']
for s in range(3):
    nX, gX = axial[s]
    w(f'    // {zones[s]}: x = {xs[s]:g}-{xs[s+1]:g} mm')
    for j in range(3):
        for k in range(3):
            verts = [v(s, j, k), v(s+1, j, k), v(s+1, j+1, k), v(s, j+1, k),
                     v(s, j, k+1), v(s+1, j, k+1), v(s+1, j+1, k+1), v(s, j+1, k+1)]
            w(f'    hex ({" ".join(map(str, verts))}) {zones[s]} ({nX} {nyz[j]} {nyz[k]})'
              f' simpleGrading ({gX} {gyz[j]} {gyz[k]})')
w(');\n\nboundary\n(')
def xface(s, j, k):
    return f'({v(s, j, k)} {v(s, j, k+1)} {v(s, j+1, k+1)} {v(s, j+1, k)})'
w('    inlet\n    {\n        type patch;\n        faces\n        (')
for j in range(3):
    for k in range(3):
        if (j, k) != (1, 1):
            w('            ' + xface(0, j, k))
w('        );\n    }')
w('    opticalWindow      // centred 25 x 25 mm window in the inlet plane\n    {\n        type patch;\n        faces\n        (')
w('            ' + xface(0, 1, 1))
w('        );\n    }')
w('    outlet\n    {\n        type patch;\n        faces\n        (')
for j in range(3):
    for k in range(3):
        w('            ' + xface(3, j, k))
w('        );\n    }')
for s in range(3):
    w(f'    {walls[s]}\n    {{\n        type wall;\n        faces\n        (')
    for k in range(3):   # y = 0
        w(f'            ({v(s,0,k)} {v(s+1,0,k)} {v(s+1,0,k+1)} {v(s,0,k+1)})')
    for k in range(3):   # y = 50
        w(f'            ({v(s,3,k+1)} {v(s+1,3,k+1)} {v(s+1,3,k)} {v(s,3,k)})')
    for j in range(3):   # z = 0
        w(f'            ({v(s,j,0)} {v(s,j+1,0)} {v(s+1,j+1,0)} {v(s+1,j,0)})')
    for j in range(3):   # z = 50
        w(f'            ({v(s,j,3)} {v(s+1,j,3)} {v(s+1,j+1,3)} {v(s,j+1,3)})')
    w('        );\n    }')
w(');\n\n// ************************************************************************* //')
open(sys.argv[1] if len(sys.argv) > 1 else 'blockMeshDict', 'w').write(
    '\n'.join(out).replace('@NW@', str(n(12))).replace('@NC@', str(n(20))) + '\n')
